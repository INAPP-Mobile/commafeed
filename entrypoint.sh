#!/bin/sh
# CommaFeed entrypoint: map Railway's PORT, start the app, seed the admin
# account exactly once per volume via the first-run setup API.
#
# Upstream facts (Athou/commafeed 7.4.1, verified in source):
# - Quarkus listens on $QUARKUS_HTTP_PORT (default 8082); Railway injects
#   PORT, so the entrypoint copies PORT into QUARKUS_HTTP_PORT on every boot.
# - GET /rest/server/get is unauthenticated (@PermitAll) and reports
#   initialSetupRequired=true while no users exist.
# - POST /rest/user/initialSetup {name, password} creates the first admin
#   (ADMIN + USER roles); it 400s once setup is done, so it is safe to call
#   only when the flag says setup is required.
# - Login is Quarkus form auth: POST /j_security_check with
#   j_username / j_password.
# - The session encryption key (QUARKUS_HTTP_AUTH_SESSION_ENCRYPTION_KEY,
#   min 16 chars) is generated by the template; without a fixed value
#   Quarkus generates a random one per boot and every login is lost on
#   restart.
set -e

export QUARKUS_HTTP_PORT="${PORT:-8082}"
BASE_URL="http://127.0.0.1:${QUARKUS_HTTP_PORT}"

# Start the app exactly as the stock image does (WORKDIR /commafeed):
# the native binary ./commafeed.
cd /commafeed
./commafeed &
APP_PID=$!

# Wait for Quarkus to answer (native boot is ~1s; allow up to 4 minutes).
SERVER_JSON=""
for _ in $(seq 1 120); do
    if SERVER_JSON=$(curl -fsS --max-time 5 "${BASE_URL}/rest/server/get" 2>/dev/null); then
        break
    fi
    sleep 2
done

if [ -z "$SERVER_JSON" ]; then
    echo "entrypoint: CommaFeed did not answer /rest/server/get within 4 minutes — failing loud"
    kill "$APP_PID" 2>/dev/null || true
    exit 1
fi

# Seed the admin account once per volume. The generated password comes from
# the template variable; changing it later does NOT reset the admin password
# (setup only runs while no users exist).
case "$SERVER_JSON" in
    *initialSetupRequired*true*)
        if [ -z "${COMMAFEED_ADMIN_PASSWORD:-}" ]; then
            echo "entrypoint: initial setup required but COMMAFEED_ADMIN_PASSWORD is not set — failing loud"
            kill "$APP_PID" 2>/dev/null || true
            exit 1
        fi
        echo "entrypoint: seeding initial admin account"
        curl -fsS --max-time 10 -X POST "${BASE_URL}/rest/user/initialSetup" \
            -H 'Content-Type: application/json' \
            -d "{\"name\":\"admin\",\"password\":\"${COMMAFEED_ADMIN_PASSWORD}\"}" \
            >/dev/null
        echo "entrypoint: admin account seeded"
        ;;
    *)
        echo "entrypoint: initial setup already completed, skipping admin seed"
        ;;
esac

# Hand the container over to the app process.
wait "$APP_PID"
